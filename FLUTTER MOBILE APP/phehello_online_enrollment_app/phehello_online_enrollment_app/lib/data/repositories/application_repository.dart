typedef ProgressCallback = void Function(String message, double fraction);

class SubmissionResult {
  const SubmissionResult(this.applicationId, this.referenceNumber);
  final String applicationId;
  final String referenceNumber;
}

/// FR2, FR3, FR4, FR5, FR15 - applications, documents, payments, status.
class ApplicationRepository {
  SupabaseClient get _c => SupabaseService.client;

  static const String _select =
      '*, '
      'learners(*, learner_medical_info(*)), '
      'application_documents(*), '
      'payments(*), '
      'application_status_history(*)';

  // ---------------------------------------------------------------- reading

  /// All applications submitted by this parent, newest first. Status values
  /// come straight from the database (never hard-coded).
  Future<List<EnrolmentApplication>> fetchMine(String userId) async {
    final rows = await _c
        .from(Db.applications)
        .select(_select)
        .eq('submitted_by', userId)
        .order('submitted_at', ascending: false);
    return (rows as List)
        .map(
          (e) =>
              EnrolmentApplication.fromMap(Map<String, dynamic>.from(e as Map)),
        )
        .toList();
  }

  Future<EnrolmentApplication?> fetchOne(String applicationId) async {
    final row = await _c
        .from(Db.applications)
        .select(_select)
        .eq('application_id', applicationId)
        .maybeSingle();
    if (row == null) return null;
    return EnrolmentApplication.fromMap(Map<String, dynamic>.from(row));
  }

  // ------------------------------------------------------------- submission

  String _extensionOf(PickedDocument f) => f.extension;

  /// Short-lived link to the confirmation letter PDF generated by the school.
  Future<String> confirmationLetterUrl(String applicationId) {
    return _c.storage
        .from(Db.bucket)
        .createSignedUrl('confirmation-letters/$applicationId.pdf', 300);
  }

  /// Downloads the confirmation letter PDF bytes.
  Future<Uint8List> downloadConfirmationLetter(String applicationId) {
    return _c.storage
        .from(Db.bucket)
        .download('confirmation-letters/$applicationId.pdf');
  }

  Future<String> _upload(String path, PickedDocument file) async {
    await _c.storage
        .from(Db.bucket)
        .uploadBinary(
          path,
          Uint8List.fromList(file.bytes),
          fileOptions: FileOptions(
            contentType: file.contentType,
            upsert: false,
          ),
        );
    return path;
  }

  /// Uploads all files to Supabase Storage, then stores the whole application
  /// in one database transaction (RPC `submit_enrolment`). Nothing is stored
  /// in the database unless every upload succeeded.
  Future<SubmissionResult> submitApplication({
    required String userId,
    required String applicationId,
    required EnrolmentDraft draft,
    required Map<DocumentType, PickedDocument> documents,
    required PickedDocument proof,
    required ProgressCallback onProgress,
    Map<String, String>? alreadyUploaded,
  }) async {
    final uploaded = alreadyUploaded ?? <String, String>{};
    final total = documents.length + 1;
    var done = 0;
    final stamp = DateTime.now().millisecondsSinceEpoch;

    final docPayload = <Map<String, dynamic>>[];
    for (final entry in documents.entries) {
      final type = entry.key;
      final file = entry.value;
      onProgress('Uploading ${type.label}...', done / total);
      final key = 'doc_${type.name}';
      final path =
          uploaded[key] ??
          await _upload(
            '$userId/$applicationId/documents/${type.name}_$stamp.${_extensionOf(file)}',
            file,
          );
      uploaded[key] = path;
      docPayload.add({
        'document_type': type.dbValue,
        'file_name': file.name,
        'storage_path': path,
      });
      done++;
    }

    onProgress('Uploading proof of payment...', done / total);

    final proofPath =
        uploaded['proof'] ??
        await _upload(
          '$userId/payment-proofs/$applicationId/proof_$stamp.${_extensionOf(proof)}',
          proof,
        );

    uploaded['proof'] = proofPath;
    done++;

    onProgress('Saving your application...', done / total);
    final payload = {
      'application_id': applicationId,
      'grade_applied_for': draft.gradeApplied,
      'learner': {
        'first_name': draft.firstName.trim(),
        'middle_name': draft.middleName.trim(),
        'surname': draft.surname.trim(),
        'initials': draft.initials.trim(),
        'other_names': draft.otherNames.trim(),
        'id_number': draft.idNumber.replaceAll(' ', ''),
        'date_of_birth': draft.dateOfBirth == null
            ? null
            : Formatters.isoDate(draft.dateOfBirth!),
        'gender': draft.gender,
        'previous_school_name': draft.previousSchool.trim(),
        'highest_grade_passed': draft.highestGradePassed,
        'year_grade_passed': draft.yearPassed.trim(),
        'school_history_notes': draft.schoolHistoryNotes.trim(),
      },
      'medical': {
        'medical_aid_name': draft.medicalAidName.trim(),
        'medical_aid_number': draft.medicalAidNumber.trim(),
        'medical_aid_main_member': draft.mainMember.trim(),
        'doctor_name': draft.doctorName.trim(),
        'doctor_address': draft.doctorAddress.trim(),
        'siblings_at_school': draft.siblingsAtSchool.trim(),
      },
      'guardian': {
        'full_name': draft.guardianName.trim(),
        'relationship_to_learner': draft.relationship,
        'phone_number': draft.guardianPhone.trim(),
      },
      'documents': docPayload,
      'payment': {
        'payment_reference': draft.paymentReference.trim(),
        'amount': Validators.parseAmount(draft.amountPaid) ?? 0,
        'proof_file_name': proof.name,
        'proof_storage_path': proofPath,
      },
    };

    final result = await _c.rpc(Db.rpcSubmit, params: {'p_payload': payload});
    String ref = '';
    if (result is Map) {
      ref = (result['reference_number'] as String?) ?? '';
    }
    onProgress('Done', 1);
    return SubmissionResult(applicationId, ref);
  }

  // ----------------------------------------------- corrections / resubmission

  /// Replaces one supporting document on an existing application
  /// (used when the school requests corrections - FR10).
  Future<void> replaceDocument({
    required String userId,
    required String applicationId,
    required DocumentType type,
    required PickedDocument file,
  }) async {
    final stamp = DateTime.now().millisecondsSinceEpoch;
    final path = await _upload(
      '$userId/$applicationId/documents/${type.name}_$stamp.${file.extension}',
      file,
    );
    await _c.rpc(
      Db.rpcReplaceDocument,
      params: {
        'p_payload': {
          'application_id': applicationId,
          'document_type': type.dbValue,
          'file_name': file.name,
          'storage_path': path,
        },
      },
    );
  }

  /// Uploads a new proof of payment after a rejection. A new payments row is
  /// inserted so the history of attempts is preserved (SRS Decision 1).
  Future<void> resubmitPaymentProof({
    required String userId,
    required String applicationId,
    required String reference,
    required double amount,
    required PickedDocument file,
  }) async {
    final stamp = DateTime.now().millisecondsSinceEpoch;

    final path = await _upload(
      '$userId/payment-proofs/$applicationId/proof_$stamp.${file.extension}',
      file,
    );

    await _c.rpc(
      Db.rpcResubmitPayment,
      params: {
        'p_payload': {
          'application_id': applicationId,
          'payment_reference': reference.trim(),
          'amount': amount,
          'proof_file_name': file.name,
          'proof_storage_path': path,
        },
      },
    );
  }

  /// Sends a "Corrections Requested" application back to the administrator.
  Future<void> resubmitForReview(String applicationId) async {
    await _c.rpc(
      Db.rpcResubmitReview,
      params: {'p_application_id': applicationId},
    );
  }

  Future<void> deleteApplication({
    required String userId,
    required EnrolmentApplication app,
  }) async {
    final paths = <String>{
      for (final d in app.documents)
        if (d.storagePath.isNotEmpty) d.storagePath,
      for (final p in app.payments)
        if (p.proofStoragePath.isNotEmpty) p.proofStoragePath,
    };

    // Sweep the folders too, so replaced / older uploads are removed.
    for (final folder in [
      '$userId/${app.id}/documents',
      '$userId/payment-proofs/${app.id}',
    ]) {
      try {
        final files = await _c.storage.from(Db.bucket).list(path: folder);
        for (final f in files) {
          paths.add('$folder/${f.name}');
        }
      } catch (_) {}
    }

    await _c.rpc(Db.rpcDeleteApplication, params: {'p_application_id': app.id});

    // The school's confirmation letter, if any (allowed once the row is gone).
    paths.add('confirmation-letters/${app.id}.pdf');

    try {
      await _c.storage.from(Db.bucket).remove(paths.toList());
    } catch (_) {}
  }

  static String describeError(Object e) => AppError.message(e);
}
