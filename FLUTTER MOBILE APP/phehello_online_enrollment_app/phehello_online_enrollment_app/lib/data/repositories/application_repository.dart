// FILE PURPOSE: application_repository.dart is the data-access class for enrolment applications.
// It reads the parent's applications from Supabase, uploads documents and proof of payment to
// Supabase Storage, submits a whole application in one database call, handles corrections and
// resubmission, serves the confirmation letter, and lets a parent delete their own application.

